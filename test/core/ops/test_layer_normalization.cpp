// Note: another shape=[49] lut will be generated by qtlib, so this binary cannot directly use in aipugt or aipurun
class OpTestLayerNorm : public OpTestBase
{
public:
    OpTestLayerNorm() {};
    virtual ~OpTestLayerNorm() {};
    bool run_test() override
    {
        GraphPtr g = Graph::create("test_layer_norm");
        auto inp = ops::input({1, 2, 8, 4}, Tensor::Dtype::UINT8, {1.0, 128}, g);

        std::vector<int8_t> weight_val(32, 8);
        int8_t *new_weight_val = new int8_t[weight_val.size()];
        memcpy(new_weight_val, weight_val.data(), weight_val.size() * sizeof(int8_t));
        auto weight = ops::make_weight(g, new_weight_val, TensorShape(8, 4), Tensor::Dtype::INT8, Quantization(1.0, 20));

        std::vector<int32_t> bias_val(32, 160);
        int32_t *new_bias_val = new int32_t[bias_val.size()];
        memcpy(new_bias_val, bias_val.data(), bias_val.size() * sizeof(int32_t));
        auto bias = ops::make_bias(g, new_bias_val, bias_val.size() * sizeof(int32_t), Tensor::INT32, Quantization(1.0, 30));
        bias->shape() = TensorShape(8, 4);
        auto a = ops::layer_normalization(inp, weight, bias, {2, 3}, 1e-5f);
        if (!a[0])
        {
            return false;
        }

        g->to_png("layer_norm.png");
        g->serialize("graph_layer_norm.def", "weight_layer_norm.bin");

        return true;
    }
};

