// Note: another shape=[49] lut will be generated by qtlib, so this binary cannot directly use in aipugt or aipurun
class OpTestInstanceNorm : public OpTestBase
{
public:
    OpTestInstanceNorm() {};
    virtual ~OpTestInstanceNorm() {};
    bool run_test() override
    {
        GraphPtr g = Graph::create("test_instance_norm");
        auto inp = ops::input({1, 1, 40, 4}, Tensor::Dtype::UINT8, {1.0, 128}, g);

        std::vector<int8_t> weight_val = {1, 2, 3, 4};
        int8_t *new_weight_val = new int8_t[weight_val.size() * sizeof(weight_val)];
        memcpy(new_weight_val, weight_val.data(), weight_val.size() * sizeof(int8_t));
        auto weight = ops::make_weight(g, new_weight_val, TensorShape(4), Tensor::INT8, Quantization(1.0, 20));

        std::vector<int32_t> bias_val = {5, 6, 7, 8};
        int32_t *new_bias_val = new int32_t[bias_val.size() * sizeof(bias_val)];
        memcpy(new_bias_val, bias_val.data(), bias_val.size() * sizeof(int32_t));
        auto bias = ops::make_bias(g, new_bias_val, bias_val.size() * sizeof(int32_t), Tensor::INT32, Quantization(1.0, 30));

        auto a = ops::instance_normalization(inp, weight, bias, 1e-5f, Quantization(1.0, 100));
        if (!a)
        {
            return false;
        }

        g->to_png("instance_norm.png");
        g->serialize("graph_instance_norm.def", "weight_instance_norm.bin");

        return true;
    }
};

class OpTestInstanceNorm16Bit : public OpTestBase
{
public:
    OpTestInstanceNorm16Bit() {};
    virtual ~OpTestInstanceNorm16Bit() {};
    bool run_test() override
    {
        GraphPtr g = Graph::create("test_instance_norm_16bit");
        auto inp = ops::input({1, 1, 40, 4}, Tensor::Dtype::UINT16, {2.0, 32768}, g);

        std::vector<int16_t> weight_val = {1, 2, 3, 4};
        int16_t *new_weight_val = new int16_t[weight_val.size()];
        memcpy(new_weight_val, weight_val.data(), weight_val.size() * sizeof(int16_t));
        auto weight = ops::make_weight(g, new_weight_val, TensorShape(weight_val.size()), Tensor::INT16, Quantization(1.0, 20));

        std::vector<int32_t> bias_val = {5, 6, 7, 8};
        int32_t *new_bias_val = new int32_t[bias_val.size()];
        memcpy(new_bias_val, bias_val.data(), bias_val.size() * sizeof(int32_t));
        auto bias = ops::make_bias(g, new_bias_val, bias_val.size() * sizeof(int32_t), Tensor::INT32, Quantization(1.0, 30));

        auto a = ops::instance_normalization(inp, weight, bias, 1e-5f, Quantization(1.0, 100));
        if (!a)
        {
            return false;
        }

        g->to_png("instance_norm_16bit.png");
        g->serialize("graph_instance_norm_16bit.def", "weight_instance_norm_16bit.bin");

        return true;
    }
};

