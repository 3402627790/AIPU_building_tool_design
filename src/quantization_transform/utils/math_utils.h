template <typename T>
void cartesian_recursive(const std::vector<std::vector<T>> &sets,
                         std::vector<T> &current,
                         std::vector<std::vector<T>> &result,
                         uint32_t index)
{
    // save the set
    if (index == sets.size())
    {
        result.push_back(current);
        return;
    }

    // recursively process the next set
    for (auto element : sets[index])
    {
        current[index] = element;
        cartesian_recursive(sets, current, result, index + 1);
    }
}

// Calculate the Cartesian product of any number of sets and return all combinations
template <typename T>
std::vector<std::vector<T>> cartesian_product(const std::vector<std::vector<T>> &sets)
{
    std::vector<std::vector<T>> result;
    if (sets.empty())
        return result;

    std::vector<T> current(sets.size());
    cartesian_recursive(sets, current, result, 0);

    return result;
}
