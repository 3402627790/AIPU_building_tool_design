def fexp(f_vdata):
    mantisa_bit = 16
    lut_bits = 9
    vshape = f_vdata.shape
#     x24 = float32_to_hex24(vx.flatten())
#     x16 = fp24_to_fp16(x24)
#     x24 = fp16_to_fp24(x16)
#     x = hex24_to_float32(x24)

    # limit input
    f_vdata = (f_vdata < -126.9)*-126.9+f_vdata*(f_vdata >= -126.9)
    f_vdata = (f_vdata > 126.9)*126.9+f_vdata*(f_vdata < 126.9)
    # f_vdata = ((f_vdata+1)*(f_vdata>=0) + (f_vdata-1)*(f_vdata<0)).flatten()
#     x = float32_to_hex24(fvata)
# #     x16 = fp24_to_fp16(x24)
# #     x = fp16_to_fp24(x16)

#     decimal,ind,diff = get_decimal_and_ind(x,lut_bits)
#     torch_pow2_lut = torch.tensor(pow2_lut).to(vx.device)
#     xlut = lut_post(decimal,torch_pow2_lut[ind],torch_pow2_lut[ind+1],diff)
#     # x16 = fp24_to_fp16(xlut)
#     # x = fp16_to_fp24(x16)
#     pow2_factor = hex24_to_float32(xlut)
    exponent = f_vdata.floor()
    mantisa = ((f_vdata - exponent)*((1 << mantisa_bit)-1)).long()
    index = mantisa >> 7

    interp_bit = mantisa & 0x7f

    torch_pow2_f_lut = torch.tensor(pow2_f_lut).to(f_vdata.device)
    diff = torch_pow2_f_lut[index+1] - torch_pow2_f_lut[index]
    post_lut = torch_pow2_f_lut[index] + (diff*interp_bit)*(2.0**-7)

    pow2_factor = post_lut*(2.0**exponent)
    pow2_fp24 = ((pow2_factor).view(torch.int) & 0xffffFF00).view(torch.float32)
    # pow2_fp16 = fp24_to_fp16(pow2_fp24)

    return pow2_fp24.reshape(vshape)


def mse(a, b):
    return (np.mean((a-b)**2))


def test_fexp(lpcnt, max_v):
    data = np.random.uniform(-88, max_v, 65536).astype(np.float32)
    data = torch.tensor(data)
    datahex = float32_to_hex24(data)
    x16 = fp24_to_fp16(datahex)
    x24 = fp16_to_fp24(x16)
    data = hex24_to_float32(x24)
    gt = np.exp(data.numpy())
    lutres = fexp(data).numpy()
    error = mse(gt, lutres)
    for i in range(lpcnt):
        data = np.random.uniform(-88, max_v, 65536).astype(np.float32)
        data = torch.tensor(data)
        datahex = float32_to_hex24(data)
        x16 = fp24_to_fp16(datahex)
        x24 = fp16_to_fp24(x16)
        data = hex24_to_float32(x24)
        gt = np.exp(data.numpy())
        lutres = fexp(data).numpy()
        error = (mse(gt, lutres)+error)/2
    return error
