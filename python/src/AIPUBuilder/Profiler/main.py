import json
import argparse
import os
import sys
# PKG_DIR = os.path.join(os.path.dirname(__file__), "../../../src/")
# sys.path.insert(0, PKG_DIR)
import re
import numpy as np
from AIPUBuilder.logger import *
from AIPUBuilder.core import Target
from AIPUBuilder.utils import is_elf_file
from AIPUBuilder.Profiler.X1.gen_report_x1 import x1_gen_report
from AIPUBuilder.Profiler.X2.gen_report_x2 import x2_gen_report
from AIPUBuilder.Profiler.extra_info import get_extra_info_from_bin
from AIPUBuilder._C._builder import ISAType


def main():
    LOGGER.reset()
    args = argparse.ArgumentParser(
        description="Profiler report generate tools")

    args.add_argument("graphjson_path",
                      help="The path of graph.json or elf file generated by buildtool")
    args.add_argument("result_bin_path",
                      help="The path of profiler result binary file generated by runtime")
    args.add_argument("-o", "--output", type=str, default="",
                      help="The output report file name")
    args.add_argument("-v", "--verbose", type=int, default=0,
                      help=argparse.SUPPRESS)
    args.add_argument("-m", "--method", type=str, default="html",
                      help="The output file format, only support html/xlsx/json")
    args.add_argument("-f", "--frequency", type=int,
                      help="Set as the frequency used for calculate time via cycles")

    args.add_argument("-db", "--database", action="store_true",
                      help="Commit the perf data into internal database")

    args.add_argument("-p", "--platform", type=str, default="fpga",
                      help="The platform of this performance data, one of [fgpa, soc, emulator, spm]")

    args.add_argument("-gv", "--gbversion", type=str, default="",
                      help="The commit id of Gbuilder")
    args.add_argument("-c", "--comment", type=str, default="",
                      help="The comment/label will be record into interenel database")

    args = args.parse_args()
    if is_elf_file(args.graphjson_path):
        from AIPUBuilder.core import AIPUELF
        elf = AIPUELF()
        elf.load(args.graphjson_path)
        graph_json = json.loads(elf.graphjson)
    else:
        with open(args.graphjson_path, "r") as f:
            graph_json = json.loads(f.read())
    binary = np.fromfile(args.result_bin_path, dtype="uint8")
    get_extra_info_from_bin(graph_json, binary)

    target_str = graph_json["platform target"]
    target = Target()
    target.set_target(target_str)
    isa_type = target.isa.value
    if isa_type >= ISAType.ZYv5:
        # X2 or newer
        x2_gen_report(graph_json, binary, args)
    else:
        # X1 or older
        x1_gen_report(graph_json, binary, args)


if __name__ == "__main__":
    main()
