import json
from typing import Dict, List, Union, Optional
from os import PathLike
from pathlib import Path
from AIPUBuilder.logger import *
from AIPUBuilder.core import Target
import numpy as np
from AIPUBuilder.Profiler.X1.get_data_x1 import x1_get_data
from AIPUBuilder.Profiler.X2.load_perf_data import load_perf_data
from AIPUBuilder.Profiler.X2.export_json import export_json
from .extra_info import get_extra_info_from_bin
from AIPUBuilder._C._builder import ISAType


def get_profiler_data(graph_json, perf_data: Union[str, PathLike, Path, np.ndarray, bytes, bytearray], **kwargs) -> Dict:
    """Get final profiler result

    Parameters
    ----------
    graph_json : str or json.object
        The graph.json path, graph.json is generated by gbuilder when enable profile

    perf_data : str or numpy array
        The binary path, which is profiler buffer data generated when run.
        Dumped using UMD or auto dumped by emulator

    Returns
    -------
    result : dict
        The dictory of the profile result.
    """

    LOGGER.reset()

    verbose = 0
    freq = 1000
    if "frequency" in kwargs:
        freq = kwargs["frequency"]

    if isinstance(graph_json, (str, PathLike, Path)):
        with open(graph_json, "r") as f:
            graph_json = json.loads(f.read())
    if isinstance(perf_data, (str, PathLike, Path)):
        perf_data = np.fromfile(perf_data, dtype="uint8")
    get_extra_info_from_bin(graph_json, perf_data)

    target_str = graph_json["platform target"]
    target = Target()
    target.set_target(target_str)
    isa_type = target.isa.value
    if isa_type >= ISAType.ZYv5:
        perf_data = load_perf_data(graph_json, perf_data, freq, verbose)
        return export_json(graph_json, perf_data, freq)
    else:
        return x1_get_data(graph_json, perf_data, **kwargs)
    return dict()
